function setLang(l){
  const d=I18N[l]||I18N.en;
  document.documentElement.lang = l==='zh'?'zh-Hant':'en';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const k=el.getAttribute('data-i18n');
    if(d[k]!==undefined){
      if(d[k].includes('\n')) el.innerHTML=d[k].replace(/\n/g,'<br>');
      else el.textContent=d[k];
    }
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const k=el.getAttribute('data-i18n-ph');
    if(d[k]!==undefined) el.placeholder=d[k];
  });
  document.querySelectorAll('.lang button').forEach(b=>b.classList.toggle('active',b.dataset.l===l));
  document.dispatchEvent(new CustomEvent('okaylang',{detail:l}));
  try{localStorage.setItem('okaylight_lang',l);}catch(e){}
}
